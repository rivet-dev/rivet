#!/usr/bin/env python3
"""Fails when a BARE schema that an OSS release shipped changes.

A released schema version is frozen: readers on that release decode it as it shipped, so any
change belongs in a new version with converters. `released-schemas.lock` pins every `.bare` file
any release tag (pre-releases included) contains, anywhere in the repository, keyed by path, by a
hash of its declarations with comments and whitespace removed, so documentation edits stay
allowed. Deleting a version no binary reads any more is allowed; the check lists such files as a
note so a deletion is never silent.

    released_schemas.py            Check the working tree against the lock.
    released_schemas.py --update   Rewrite the lock from the release tags in the local Git
                                   repository. Nothing runs it automatically: after each OSS
                                   release, fetch its tags (`git fetch <oss remote> --tags`), run
                                   `just schemas-pin-released` and commit the lock.

Each file is pinned to the latest release that contains it, except the overrides below.
"""

import argparse
import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LOCK = os.path.join(ROOT, "scripts", "schemas", "released-schemas.lock")

# Files whose pin is not the latest release that contains them. Each entry names the release
# whose content the repository keeps and why.
OVERRIDES = {
    # 3.0.3 through 3.0.7 edited released v3 in place. The edit now lives in v4, and v3 is the
    # layout 3.0.2 shipped; see engine/sdks/rust/data/src/versioned/pegboard_actor/mod.rs.
    "engine/sdks/schemas/data/pegboard.actor.v3.bare": "v3.0.2",
}


def normalized(source: str) -> str:
    lines = []
    for line in source.splitlines():
        line = line.strip()
        if line.startswith("#import"):
            lines.append("import " + line[len("#import"):].strip().strip('"'))
            continue
        code = line.split("#", 1)[0].split()
        if code:
            lines.append(" ".join(code))
    return "\n".join(lines) + "\n"


def fingerprint(source: str) -> str:
    return hashlib.sha256(normalized(source).encode()).hexdigest()


def release_key(tag: str):
    match = re.fullmatch(r"v(\d+)\.(\d+)\.(\d+)(?:-(.+))?", tag)
    if not match:
        return None
    major, minor, patch, pre = match.groups()
    # A pre-release sorts before its release.
    # Numeric identifiers sort before alphanumeric ones, as in semver.
    identifiers = [(0, int(part), "") if part.isdigit() else (1, 0, part) for part in re.split(r"[.-]", pre or "")]
    pre_key = (0, identifiers) if pre else (1, [])
    return (int(major), int(minor), int(patch), pre_key)


def git(*args: str) -> str:
    return subprocess.check_output(["git", *args], cwd=ROOT, text=True)


def update() -> None:
    tags = [tag for tag in git("tag", "-l", "v*").split() if release_key(tag) is not None]
    tags.sort(key=release_key)
    pins = {}
    for tag in tags:
        listing = git("ls-tree", "-r", "--name-only", tag)
        for path in listing.split():
            if not path.endswith(".bare"):
                continue
            pinned_tag = OVERRIDES.get(path)
            if pinned_tag is not None and release_key(tag) > release_key(pinned_tag):
                continue
            pins[path] = (tag, fingerprint(git("show", f"{tag}:{path}")))
    for path, tag in OVERRIDES.items():
        if path not in pins or pins[path][0] != tag:
            sys.exit(f"override {path} names {tag}, which does not contain it")
    with open(LOCK, "w") as out:
        out.write("# Generated by scripts/schemas/released_schemas.py --update. Do not edit.\n")
        out.write("# <normalized sha256> <release> <path>\n")
        for path in sorted(pins):
            tag, digest = pins[path]
            out.write(f"{digest} {tag} {path}\n")
    print(f"pinned {len(pins)} released schema files from {len(tags)} releases")


def check() -> None:
    failures = []
    deleted = []
    with open(LOCK) as lock:
        for line in lock:
            if line.startswith("#") or not line.strip():
                continue
            digest, tag, path = line.split()
            full = os.path.join(ROOT, path)
            # Dropping a version no binary reads any more is allowed; changing one is not.
            if not os.path.exists(full):
                deleted.append(f"{path} (shipped in {tag})")
                continue
            with open(full) as source:
                if fingerprint(source.read()) != digest:
                    failures.append(f"{path}: differs from the version {tag} shipped")
    if deleted:
        print(f"note: {len(deleted)} released schema files are no longer in the tree:")
        for path in deleted:
            print(f"  {path}")
    if failures:
        print("Released schema versions are frozen. Add a new version with converters instead:")
        for failure in failures:
            print(f"  {failure}")
        sys.exit(1)
    print("released schemas unchanged")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--update", action="store_true", help="rewrite the lock from release tags")
    args = parser.parse_args()
    if args.update:
        update()
    else:
        check()


if __name__ == "__main__":
    main()
